-- SQL 01 - Crear la tabla public.alumnos
create table if not exists public.alumnos (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    foto varchar(500) null,
    nombres varchar(200) not null,
    correo varchar(150) null,
    paralelo char(1) not null,
    telefono varchar(20) null
);

-- SQL 02 - Registros de demostración
insert into public.alumnos
    (nombres, paralelo, correo, telefono, foto)
values
    ('ANA EJEMPLO', 'A', 'ana@example.com', null, null),
    ('BRUNO DEMO', 'A', 'bruno@example.com', null, null),
    ('CARLA PRUEBA', 'B', 'carla@example.com', null, null);

-- SQL 03 - Consulta de comprobación
select id, nombres, paralelo, correo, telefono
from public.alumnos
order by nombres asc;

-- SQL 04 - RLS y lectura pública SOLO para el proyecto de demostración.
-- No aplicar sobre tablas con datos personales reales.
alter table public.alumnos enable row level security;

create policy "lectura_demo_alumnos"
on public.alumnos
for select
to anon
using (true);
